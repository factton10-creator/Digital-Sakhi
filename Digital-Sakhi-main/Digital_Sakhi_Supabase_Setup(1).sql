-- Digital Sakhi learner data tables
-- Run this whole script in Supabase Dashboard → SQL Editor → New query.
-- The website uses the publishable/anon key and has INSERT-only access to these tables.
-- Public visitors cannot read learner data through the API.

create table if not exists public.learner_profiles (
  id bigint generated by default as identity primary key,
  learner_id text not null,
  learner_name text not null,
  age_group text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.baseline_assessments (
  id bigint generated by default as identity primary key,
  learner_id text not null,
  submitted_at timestamptz not null default now(),
  smartphone_use text,
  digital_payments_confidence text,
  cyber_safety_confidence text,
  internet_email_confidence text,
  confidence_score integer check (confidence_score between 1 and 5),
  priority_skill text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.skill_completions (
  id bigint generated by default as identity primary key,
  learner_id text not null,
  skill_key text not null check (skill_key in ('phone','upi','cyber','internet','services','work')),
  skill_name text not null,
  completed_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  learner_id text not null,
  score integer not null check (score between 0 and 3),
  total_questions integer not null default 3 check (total_questions = 3),
  attempted_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create table if not exists public.program_completions (
  id bigint generated by default as identity primary key,
  learner_id text not null,
  completed_at timestamptz not null default now(),
  skills_completed integer not null check (skills_completed = 6),
  created_at timestamptz not null default now()
);

alter table public.learner_profiles enable row level security;
alter table public.baseline_assessments enable row level security;
alter table public.skill_completions enable row level security;
alter table public.quiz_attempts enable row level security;
alter table public.program_completions enable row level security;

-- Drop/recreate policies safely if the script is run more than once.
drop policy if exists "Public can submit learner profiles" on public.learner_profiles;
drop policy if exists "Public can submit baseline assessments" on public.baseline_assessments;
drop policy if exists "Public can submit skill completions" on public.skill_completions;
drop policy if exists "Public can submit quiz attempts" on public.quiz_attempts;
drop policy if exists "Public can submit program completions" on public.program_completions;

create policy "Public can submit learner profiles" on public.learner_profiles for insert to anon, authenticated with check (true);
create policy "Public can submit baseline assessments" on public.baseline_assessments for insert to anon, authenticated with check (true);
create policy "Public can submit skill completions" on public.skill_completions for insert to anon, authenticated with check (true);
create policy "Public can submit quiz attempts" on public.quiz_attempts for insert to anon, authenticated with check (true);
create policy "Public can submit program completions" on public.program_completions for insert to anon, authenticated with check (true);

-- No SELECT, UPDATE, or DELETE policies are created for these tables.
